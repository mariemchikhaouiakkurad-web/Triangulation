% MAKE_GEOMETRY_CFGS  Write uma16.cfg and uma8.cfg (ODAS-style mic lists) for tri_tdoa_combine.
%
%   uma16.cfg : UMA-16 v2 silk-screen layout (4x4, 42 mm pitch), row i = USB channel i = MICi
%   uma8.cfg  : your calibrated UMA-8 geometry from uma8_geometry.mat (channels 1-7)
%
%   >> make_geometry_cfgs
%
% Board frame: x right, y up, z out of the mic face (viewed from the MIC side).

pitch = 0.042;
layout = [ 8  7 10  9 ;        % MIC numbers as printed, viewed from the mic side
           6  5 12 11 ;
           4  3 14 13 ;
           2  1 16 15 ];
xCol = [-1.5 -0.5 0.5 1.5] * pitch;
yRow = [ 1.5  0.5 -0.5 -1.5] * pitch;
p16 = nan(16, 3);
for r = 1:4
    for c = 1:4
        p16(layout(r, c), :) = [xCol(c), yRow(r), 0];
    end
end
write_cfg('uma16.cfg', p16, 'UMA-16 v2, MICn = channel n');

geo8 = 'uma8_geometry.mat';
if ~isfile(geo8), geo8 = fullfile('..', '..', 'uma8_geometry.mat'); end   % Downloads\uma8_geometry.mat
if isfile(geo8)
    s = load(geo8);
    p8 = s.micPos;
    note = sprintf('UMA-8 calibrated geometry from %s', geo8);
else
    a = (0:5)' * 60;                                     % fallback: centre + 6-mic ring
    p8 = [0 0 0; 0.043 * [cosd(a), sind(a), zeros(6, 1)]];
    note = 'UMA-8 nominal geometry (uma8_geometry.mat not found)';
end
write_cfg('uma8.cfg', p8, note);


function write_cfg(file, P, note)
fid = fopen(file, 'w');
fprintf(fid, '# %s\n# generated by make_geometry_cfgs.m\nmics = (\n', note);
for i = 1:size(P, 1)
    fprintf(fid, '    { mu = (%.5f, %.5f, %.5f); }%s\n', P(i, :), repmat(',', 1, i < size(P, 1)));
end
fprintf(fid, ');\nmapping: { map: (%s); }\n', strjoin(string(1:size(P, 1)), ', '));
fclose(fid);
fprintf('wrote %s (%d mics) - %s\n', file, size(P, 1), note);
end
